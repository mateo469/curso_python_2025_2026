#Importar el modulo math
import math

math.sqrt(25)       # Raíz cuadrada → 5.0
math.pow(2, 3)      # Potencia → 8.0
math.factorial(5)   # Factorial → 120
math.pi             # Constante pi → 3.141592...
math.sin(math.pi/2) # Seno → 1.0
math.log(100, 10)   # Logaritmo base 10 → 2.0

